"""Write requirements.txt with every release file's SHA-256 for each pinned version.

    python3 -I packaging/flatpak/pin-requirements.py > packaging/flatpak/requirements.txt

PINS below is the whole list (the two packages the generator imports and what
they need, for Python 3.9 and newer). To update: change a version, run this,
read the diff. update-cargo-sources.sh installs the result with
`pip install --require-hashes --only-binary=:all:`, so a package whose files
differ from these hashes (a re-uploaded or tampered release, a dependency
that isn't listed) fails the install instead of running. Every wheel and the
source archive of a version is listed, so any Python or CPU works.
"""

import json
import sys
import urllib.request

PINS = [
    ("aiohappyeyeballs", "2.7.1", None),
    ("aiohttp", "3.13.0", None),
    ("aiosignal", "1.4.0", None),
    ("async-timeout", "5.0.1", 'python_version < "3.11"'),
    ("attrs", "26.1.0", None),
    ("frozenlist", "1.8.0", None),
    ("idna", "3.20", None),
    ("multidict", "6.9.1", None),
    ("propcache", "0.5.4", None),
    ("tomlkit", "0.13.3", None),
    ("typing-extensions", "4.15.0", 'python_version < "3.13"'),
    ("yarl", "1.25.1", None),
]


def main():
    print("# Generated by pin-requirements.py: do not edit by hand.")
    print("# Installed with --require-hashes --only-binary=:all: (update-cargo-sources.sh).")
    for name, version, marker in PINS:
        url = f"https://pypi.org/pypi/{name}/{version}/json"
        with urllib.request.urlopen(url, timeout=30) as r:
            files = json.load(r)["urls"]
        hashes = sorted({f["digests"]["sha256"] for f in files})
        if not hashes:
            sys.exit(f"no files for {name}=={version}")
        line = f"{name}=={version}"
        if marker:
            line += f" ; {marker}"
        print(line + " \\")
        print(" \\\n".join(f"    --hash=sha256:{h}" for h in hashes))
    return 0


if __name__ == "__main__":
    sys.exit(main())
